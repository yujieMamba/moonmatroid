lines += ['}','///|','test "all labeled three element matroid pairs reach exhaustive optima" {',f'  let tables : Array[Array[Int]] = {mb(small)}',f'  let optimum : Array[Array[Int]] = {mb(small_opt)}','  for i = 0; i < tables.length(); i = i + 1 {','    for j = 0; j < tables.length(); j = j + 1 {','      let a = Matroid::from_ranks(3, tables[i])','      let b = Matroid::from_ranks(3, tables[j])','      let result = intersect(a,b)','      verify_intersection(a,b,result)','      assert_eq(result.elements.length(),optimum[i][j])','    }','  }','}','///|','test "cross representation intersection and union oracle" {','  let models = ['+','.join(c['expression'] for c in cases)+']',f'  let pairs = {mb(pairs)}','  for pair in pairs {','    let result = intersect(models[pair[0]],models[pair[1]])','    verify_intersection(models[pair[0]],models[pair[1]],result)','    assert_eq(result.elements.length(),pair[2])','  }',f'  let unions = {mb(unions)}','  for item in unions {','    let ms = [models[item[0]],models[item[1]]]','    let result = union_partition(ms)','    verify_partition(ms,result.groups,result.elements)','    assert_eq(result.elements.length(),item[2])','  }','}']
